import tkinter as tk  # Подключаем библиотеку для окон

# Функция, которая будет выполняться при нажатии на кнопку
def on_button_click():
    print("Кнопка нажата!")  # Сообщение появится в терминале

# Создаём главное окно приложения
root = tk.Tk()
root.title("Моё первое окно")  # Заголовок окна

# Создаём кнопку и говорим, какую функцию вызывать при нажатии
button = tk.Button(root, text="Нажми меня", command=on_button_click)

# Размещаем кнопку в окне
button.pack()

# Запускаем главный цикл приложения (окно будет открыто, пока его не закроют)
root.mainloop()
